        private static string Change(string field, object value)
        {
            var json = new JavaScriptSerializer();
            var fields = json.Deserialize<Dictionary<string, object>>(AsciiVector); fields[field] = value;
            return json.Serialize(fields);
        }
        private static VaultReadResult Fixture(string root, string name, string json, string pin, VaultReadStatus status)
        {
            string path = Path.Combine(root, name + ".fixture"); File.WriteAllBytes(path, Encoding.UTF8.GetBytes(json));
            return ReadUnchanged(path, pin, status, name);
        }
        private static VaultReadResult ReadUnchanged(string path, string pin, VaultReadStatus status, string name)
        {
            byte[] before = File.ReadAllBytes(path);
            string[] files = Directory.GetFiles(Path.GetDirectoryName(path)).OrderBy(p => p).ToArray();
            var result = VaultService.Read(path, pin); CheckResult(result, status, path);
            Check(before.SequenceEqual(File.ReadAllBytes(path)) && files.SequenceEqual(Directory.GetFiles(Path.GetDirectoryName(path)).OrderBy(p => p)),
                name + " read leaves source bytes and file set unchanged");
            return result;
        }
        private static void CheckResult(VaultReadResult result, VaultReadStatus status, string path)
        {
            Check(result.Status == status && (status == VaultReadStatus.Success ? result.Data != null : result.Data == null),
                "typed read returns " + status + " with data only on success");
            if (status == VaultReadStatus.Success) return;
            var error = result.ToException();
            Check(error.InnerException == null && error.Message == result.ErrorMessage && !error.Message.Contains(path) &&
                !error.Message.Contains("private-json-marker") && !error.Message.Contains("fixture-only") &&
                !error.Message.Contains("1234") && !error.Message.Contains(UnicodePin), "failure projection contains only a static safe message");
        }

        private static void MaxIterations(string root)
        {
            string path = Path.Combine(root, "max-iterations.fixture");
            File.WriteAllBytes(path, Encoding.UTF8.GetBytes(Change("iterations", Int32.MaxValue)));
            byte[] before = File.ReadAllBytes(path);
            using (var child = Process.Start(new ProcessStartInfo(Assembly.GetExecutingAssembly().Location, "--max-iterations \"" + path + "\"") {
                UseShellExecute = false, CreateNoWindow = true
            })) {
                if (!child.WaitForExit(10000)) {
                    child.Kill(); child.WaitForExit(5000);
                    throw new Exception("unsupported KDF cost exceeded the isolated child deadline");
                }
                Check(child.ExitCode == 0 && before.SequenceEqual(File.ReadAllBytes(path)),
                    "maximum KDF cost is rejected by an isolated bounded child before derivation");
            }
        }

        private static void LegacyOperations(string root)
        {
            AppPaths.AllowGlobalAccess = true;
            try {
                string path = AppPaths.VaultPath;
                File.WriteAllText(path, AsciiVector);
                byte[] original = File.ReadAllBytes(path);
                var opened = VaultService.Open("1234");
                Check(opened.CanPersist && opened.Data.entries.Single().secret == "fixture-only", "actual Open routes a legacy real vector to a persistent session");
                var mismatch = VaultService.Open("4321");
                Check(!mismatch.CanPersist && mismatch.Data.entries.All(e => e.secret != "fixture-only") && original.SequenceEqual(File.ReadAllBytes(path)),
                    "only authentication mismatch retains the existing transient sample behavior");
                int logs = SafeLog.Messages.Count;
                File.WriteAllText(path, "{\"private-json-marker\":");
                byte[] bad = File.ReadAllBytes(path); Exception failure = null;
                try { VaultService.Open("1234"); } catch (Exception ex) { failure = ex; }
                Check(failure is InvalidDataException && failure.InnerException == null && !failure.Message.Contains(path) &&
                    !failure.Message.Contains("private-json-marker") && bad.SequenceEqual(File.ReadAllBytes(path)) && SafeLog.Messages.Count == logs,
                    "actual Open reports corruption without sample fallback, private details or success logging");
                foreach (var rejected in new[] {
                    Envelope("XRZycZ7iuo4VhkcN6sxg5w==", "5Fb3Klm9inAJq/rK/NHfUpQi32/ZB53d2WhAB4FMlZw="),
                    Change("iterations", 0)
                }) {
                    File.WriteAllText(path, rejected); bad = File.ReadAllBytes(path); failure = null; logs = SafeLog.Messages.Count;
                    try { VaultService.Open("1234"); } catch (Exception ex) { failure = ex; }
                    Check(failure is InvalidDataException && failure.InnerException == null && !failure.Message.Contains(path) &&
                        bad.SequenceEqual(File.ReadAllBytes(path)) && SafeLog.Messages.Count == logs,
                        "actual Open rejects authenticated invalid data or unsupported cost without a sample or success log");
                }
                File.Delete(path); failure = null;
                try { VaultService.Open("1234"); } catch (Exception ex) { failure = ex; }
                Check(failure is IOException && failure.InnerException == null && !failure.Message.Contains(path) && !File.Exists(path),
                    "actual Open of a missing vault fails safely without implicit Create");
                var created = VaultService.Create(UnicodePin);
                var entry = VaultEntry.New(); entry.name = "Synthetic saved"; entry.secret = "fixture-only";
                created.Data.entries.Add(entry); VaultService.Save(created);
                var roundtrip = VaultService.Open(UnicodePin);
                var envelope = new JavaScriptSerializer().Deserialize<VaultEnvelope>(File.ReadAllText(path));
                Check(roundtrip.CanPersist && roundtrip.Data.entries.Single().secret == entry.secret && envelope.version == 1 &&
                    envelope.kdf == "PBKDF2-HMAC-SHA256" && envelope.iterations == 120000 && envelope.cipher == "AES-256-CBC" &&
                    envelope.mac == "HMAC-SHA256" && Convert.FromBase64String(envelope.salt).Length == 32 &&
                    Convert.FromBase64String(envelope.iv).Length == 16 && Convert.FromBase64String(envelope.tag).Length == 32,
                    "actual Create Save Open preserves the v1 writer and Unicode PIN");
                original = File.ReadAllBytes(path); failure = null;
                try { VaultService.Create("9999"); } catch (Exception ex) { failure = ex; }
                Check(failure is IOException && failure.InnerException == null && !failure.Message.Contains(path) &&
                    !failure.Message.Contains("9999") && original.SequenceEqual(File.ReadAllBytes(path)),
                    "explicit Create cannot overwrite a vault that already appeared and reports a static safe failure");
                if (Environment.OSVersion.Platform == PlatformID.Win32NT) {
                    var candidate = new VaultSession(VaultData.Empty(), UnicodePin, true); bool denied = false;
                    using (var handle = File.Open(path, FileMode.Open, FileAccess.Read, FileShare.Read)) {
                        try { VaultService.Save(candidate); } catch (IOException) { denied = true; } catch (UnauthorizedAccessException) { denied = true; }
                    }
                    Check(denied && original.SequenceEqual(File.ReadAllBytes(path)), "actual denied atomic Save retains the original vault bytes");
                } else Console.WriteLine("SKIP: actual atomic replacement lock requires Windows");
                Check(!Directory.GetFiles(root, "*.tmp").Any(), "successful and refused legacy commits clean their owned staging files");
            } finally { AppPaths.AllowGlobalAccess = false; }
        }
