    // Only this harness is compiled with these guards, never Core.cs or the app's real paths.
    internal static class AppPaths
    {
        internal static string OwnedRoot;
        internal static bool AllowGlobalAccess;
        internal static int Accesses;
        public static string VaultPath { get { Guard(); return Path.Combine(OwnedRoot, "vault.enc.json"); } }
        public static void EnsureDirectories() { Guard(); Directory.CreateDirectory(OwnedRoot); }
        private static void Guard()
        {
            Accesses++;
            if (!AllowGlobalAccess || String.IsNullOrEmpty(OwnedRoot)) throw new InvalidOperationException("Global vault path guard");
        }
    }

    internal static class SafeLog
    {
        internal static int Accesses;
        internal static readonly List<string> Messages = new List<string>();
        public static void Info(string message)
        {
            Accesses++;
            if (!AppPaths.AllowGlobalAccess) throw new InvalidOperationException("Global vault log guard");
            Messages.Add(message);
        }
    }

